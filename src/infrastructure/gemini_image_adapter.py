"""Gemini Image adapter for stylized YouTube Kids thumbnail background art."""

from pathlib import Path
from typing import Any

from src.domain.errors import ThumbnailArtError

DEFAULT_IMAGE_MODEL: str = "gemini-3.1-flash-image"
THUMBNAIL_ASPECT_RATIO: str = "16:9"
MASKED_IMAGE_MIME_TYPE: str = "image/png"

THUMBNAIL_ART_PROMPT_TEMPLATE: str = (
    "Transforma la escena del videojuego de la imagen de referencia en un fondo "
    "espectacular, vibrante y súper llamativo estilo miniatura de YouTube Kids en 16:9. "
    "Contexto: {scene_prompt}. "
    "Reemplaza el rectángulo gris sólido de la esquina superior izquierda con paisaje "
    "o escenario continuo del mismo juego. Usa iluminación cinematográfica, colores "
    "saturados y composición dinámica infantil. "
    "PROHIBIDO incluir texto, letras, números, logotipos, marcas de agua o rostros humanos."
)


class GeminiImageAdapter:
    """ThumbnailArtGeneratorPort implementation using google-genai image generation."""

    def __init__(
        self,
        api_key: str | None = None,
        client: Any | None = None,
        model_name: str = DEFAULT_IMAGE_MODEL,
    ) -> None:
        if client is None:
            from google import genai  # noqa: PLC0415

            client = genai.Client(api_key=api_key)
        self._client = client
        self._model_name = model_name

    def generate_art(
        self,
        reference_image_path: str,
        scene_prompt: str,
        output_image_path: str,
    ) -> str:
        """Send masked reference frame to Gemini Image API and persist generated bytes."""
        from google.genai import types  # noqa: PLC0415

        try:
            reference_bytes = Path(reference_image_path).read_bytes()
            image_part = types.Part.from_bytes(
                data=reference_bytes,
                mime_type=MASKED_IMAGE_MIME_TYPE,
            )
            prompt = THUMBNAIL_ART_PROMPT_TEMPLATE.format(scene_prompt=scene_prompt)
            response = self._client.models.generate_content(
                model=self._model_name,
                contents=[image_part, prompt],
                config=types.GenerateContentConfig(
                    response_modalities=["IMAGE"],
                    image_config=types.ImageConfig(aspect_ratio=THUMBNAIL_ASPECT_RATIO),
                ),
            )
        except Exception as exc:
            raise ThumbnailArtError(f"Gemini image API request failed: {exc}") from exc

        image_bytes = self._extract_image_bytes(response)
        target = Path(output_image_path)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(image_bytes)
        return str(target)

    @staticmethod
    def _extract_image_bytes(response: Any) -> bytes:
        candidates = getattr(response, "candidates", None) or []
        for candidate in candidates:
            content = getattr(candidate, "content", None)
            parts = getattr(content, "parts", None) or []
            for part in parts:
                inline_data = getattr(part, "inline_data", None)
                data = getattr(inline_data, "data", None)
                if isinstance(data, (bytes, bytearray)) and data:
                    return bytes(data)

        feedback = getattr(response, "prompt_feedback", None)
        block_reason = getattr(feedback, "block_reason", None)
        finish_reason = getattr(candidates[0], "finish_reason", None) if candidates else None
        reason = block_reason or finish_reason or "no image data returned"
        raise ThumbnailArtError(f"Gemini image generation returned no image ({reason}).")
